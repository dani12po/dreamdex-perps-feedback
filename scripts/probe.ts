import { SOMNIA_HIDEKI_TESTNET_ADDRESSES, SomniaMarkets } from "@somnia-chain/markets-sdk"
import { hidekiTestnet } from "@somnia-chain/markets-sdk/chains"
import { parseUnits } from "viem"
const J=(v:any)=>JSON.stringify(v,(k,x)=>typeof x==='bigint'?x.toString():x)
const markets = new SomniaMarkets({ chain: hidekiTestnet, indexerUrl: "https://hideki-dev.smk.somnia.host/v1/graphql", addresses: SOMNIA_HIDEKI_TESTNET_ADDRESSES, privateKey: process.env.PRIVATE_KEY as `0x${string}` })
const c:any = markets.client
const account = markets.walletAddress!
console.log("wallet", account)
console.log("ADDR", J(SOMNIA_HIDEKI_TESTNET_ADDRESSES))
const perps = await c.listPerpMarkets()
const btc = perps.find((m:any)=>m.baseSymbol==="BTC")
async function t(name:string, f:()=>Promise<any>){ const t0=Date.now(); try{ const r=await f(); console.log("OK",name,Date.now()-t0+"ms",J(r).slice(0,1500)) }catch(e:any){ console.log("ERR",name,Date.now()-t0+"ms",e?.constructor?.name,e?.name,(e?.message||String(e)).slice(0,800), e?.errorName??'') } }
await t("getPerpSystemConfig", ()=>c.getPerpSystemConfig(btc.marginBank))
await t("getPerpVoucherEligibility", ()=>c.getPerpVoucherEligibility(btc.marginBank, account))
await t("getPerpVoucherCampaign", ()=>c.getPerpVoucherCampaign(btc.marginBank))
await t("getPerpVoucher", ()=>c.getPerpVoucher(btc.marginBank, account))
const price = parseUnits("100000", btc.quoteDecimals)
await t("getMaxPerpOrderSize(doc example)", ()=>c.getMaxPerpOrderSize({pool:btc.poolAddress, marginBank:btc.marginBank, account, isBid:true, price}))
await t("getPerpState", ()=>c.getPerpState(btc.poolAddress))
await t("getPerpFeedStatus", ()=>c.getPerpFeedStatus(btc.poolAddress))
await t("getPerpFundingPremium", ()=>c.getPerpFundingPremium(btc.poolAddress))
await t("getPerpRiskParams", ()=>c.getPerpRiskParams(btc.poolAddress))
await t("getPerpHealthSnapshot", ()=>c.getPerpHealthSnapshot(btc.poolAddress))
await t("getPerpPosition", ()=>c.getPerpPosition({pool:btc.poolAddress, marginBank:btc.marginBank, account}))
await t("getPerpLeverage", ()=>c.getPerpLeverage({pool:btc.poolAddress, marginBank:btc.marginBank, account}))
await t("getPerpMaxLeverage", ()=>c.getPerpMaxLeverage({pool:btc.poolAddress, marginBank:btc.marginBank, account}))
await t("getPerpPortfolio", ()=>c.getPerpPortfolio(account))
await t("listPerpPositions", ()=>c.listPerpPositions(account))
await t("listPerpOrderHistory", ()=>c.listPerpOrderHistory(account))
await t("tryGetPerpAccountEquity", ()=>c.tryGetPerpAccountEquity(btc.marginBank, account))
await t("getPerpCollateralBasis", ()=>c.getPerpCollateralBasis(btc.marginBank, account))
await t("getPerpLinkedWalletRegistry", ()=>c.getPerpLinkedWalletRegistry(btc.marginBank))
await t("quotePerpFundingPayer", ()=>c.quotePerpFundingPayer(btc.marginBank, account))
await t("getPerpMainFunding", ()=>c.getPerpMainFunding(btc.marginBank, account))
await t("getPerpStopOrderSomiPayment", ()=>c.getPerpStopOrderSomiPayment(btc.stopRegistry))
await t("listPerpOrderRejections", ()=>c.listPerpOrderRejections({limit:5}))
await t("listPerpFees", ()=>c.listPerpFees({limit:3}))
await t("listPerpPoolStatuses", async()=>{const s=await c.getPerpSystemConfig(btc.marginBank); return c.listPerpPoolStatuses({factory:s.factory ?? s.perpPoolFactory ?? s.poolFactory})})
await t("getPerpSideHolders long", ()=>c.getPerpSideHolders({pool:btc.poolAddress, marginBank:btc.marginBank, isLong:true}))
await t("getOrderBook", ()=>c.getOrderBook?.(btc.poolAddress) ?? Promise.reject(new Error('no getOrderBook')))
await t("getPerpMarket", ()=>c.getPerpMarket(btc.id))
await t("listPerpInsuranceFundEvents", ()=>c.listPerpInsuranceFundEvents({limit:3}))
process.exit(0)
